#!/usr/bin/env python3
"""vst/presets.json -> src/presets_tab.h: the presets as the engine's BROWSE page applies them.

    python3 tools/make_presets_tab.py      (vst/build.sh runs it; the header is committed)

Values become what set_param() gets from the wrapper (an option's index, or the number in the parameter's own units),
the same conversion tools/gen_vst.py uses for MPC's PRESET menu, so a preset picked on BROWSE sounds exactly like the
same preset picked there. A preset's category is the tag before " | " in its name."""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
# the browser's categories, in order (after ALL): (tag, what BROWSE shows)
CATS = [("ACO", "ACOUSTIC"), ("ELE", "ELECTRIC"), ("80s", "80S"), ("BAS", "BASS"), ("STL", "STEEL & SLIDE"),
        ("HRP", "HARP"), ("VLN", "VIOLIN"), ("ZTH", "ZITHER"), ("FLK", "FOLK"), ("SYN", "SYNTH LAYERS")]


def value(p, v, where):
    opts = [str(o) for o in p.get("options") or []]
    if opts:
        low = [o.lower() for o in opts]
        if isinstance(v, str) and v.lower() in low:
            return low.index(v.lower())
        if isinstance(v, int) and not isinstance(v, bool) and 0 <= v < len(opts):
            return v
        sys.exit("%s: %s=%r is not one of %s" % (where, p["key"], v, ",".join(opts)))
    lo, hi = p.get("min", 0), p.get("max", 1)
    if isinstance(v, bool) or not isinstance(v, (int, float)) or not lo <= v <= hi:
        sys.exit("%s: %s=%r is not a number in %g..%g" % (where, p["key"], v, lo, hi))
    return int(round(v)) if p.get("display") == "int" else v


def main():
    params = {p["key"]: p for p in json.load(open(os.path.join(ROOT, "vst", "params.json")))["params"]}
    presets = json.load(open(os.path.join(ROOT, "vst", "presets.json")))["presets"]
    keys = []
    for pr in presets:
        for k in pr["values"]:
            if k not in params:
                sys.exit("presets.json: %r: %r is not a parameter" % (pr["name"], k))
            if k not in keys:
                keys.append(k)
    tags = [t for t, _ in CATS]
    cat = []
    for pr in presets:
        tag = pr["name"].split(" | ", 1)[0]
        if tag not in tags:
            sys.exit("presets.json: %r: unknown category %r (tools/make_presets_tab.py CATS)" % (pr["name"], tag))
        cat.append(tags.index(tag))
    out = ["/* generated by tools/make_presets_tab.py from vst/presets.json: edit that, not this file */",
           "#define NPRESET %d" % len(presets), "#define NPRESET_KEYS %d" % len(keys), "#define NBCAT %d" % len(CATS),
           "static const char *const BCAT_NAME[NBCAT + 1] = {\"ALL\", %s};" % ", ".join(json.dumps(n) for _, n in CATS),
           "static const char *const PRESET_KEYS[NPRESET_KEYS] = {%s};" % ", ".join('"%s"' % k for k in keys),
           "/* the name after the category tag, and the tag's index in BCAT_NAME (1..NBCAT) */",
           "static const char *const PRESET_NAME[NPRESET] = {%s};" % ", ".join(json.dumps(p["name"].split(" | ", 1)[-1]) for p in presets),
           "static const signed char PRESET_CAT[NPRESET] = {%s};" % ", ".join(str(c + 1) for c in cat),
           "/* NAN: the preset leaves that parameter as it is */",
           "static const float PRESET_VAL[NPRESET][NPRESET_KEYS] = {"]
    for pr in presets:
        out.append("    {%s}," % ", ".join("%g" % value(params[k], pr["values"][k], pr["name"]) if k in pr["values"] else "NAN"
                                          for k in keys))
    out.append("};")
    open(os.path.join(ROOT, "src", "presets_tab.h"), "w").write("\n".join(out) + "\n")
    print("presets_tab.h: %d presets, %d keys, %d categories" % (len(presets), len(keys), len(CATS)))


if __name__ == "__main__":
    main()
